"""Writes src/lib/logoMark.ts: the logo mark's outline for use in the website,
so the site and the brand pack are always drawn from the same geometry.

    python export_site_paths.py
"""
import re
from pathlib import Path
import logo

svg = logo.mark_svg(None, "#000", "#000", transparent=True)
h_d = re.search(r'<path d="([^"]+)" fill="#000"/>', svg).group(1)
roof = re.search(r'<path d="(M[^"]+)" fill="none" stroke="#000" stroke-width="([\d.]+)"', svg)
roof_d, sw = roof.group(1), float(roof.group(2))

# Tight bounds of the artwork (so it sits snugly beside text), with the stroke included.
nums = [float(n) for n in re.findall(r"-?\d+\.?\d*", h_d)]
rn = [float(n) for n in re.findall(r"-?\d+\.?\d*", roof_d)]
rx, ry = rn[0::2], rn[1::2]
xs = nums[0::2] + [min(rx) - sw / 2, max(rx) + sw / 2]
ys = nums[1::2] + [min(ry) - sw / 2]
pad = 4
x0, y0 = min(xs) - pad, min(ry) - sw / 2 - pad
x1 = max(xs) + pad
y1 = max(nums[1::2]) + pad  # H baseline
box = f"{x0:.1f} {y0:.1f} {x1 - x0:.1f} {y1 - y0:.1f}"

out = Path(__file__).resolve().parents[2] / "src" / "lib" / "logoMark.ts"
out.write_text(f'''// Generated by brand/source/export_site_paths.py. Do not edit by hand.
// The Open Home Hero mark: an open roof over a serif H.

export const LOGO_H_PATH =
  "{h_d}";
export const LOGO_ROOF_PATH = "{roof_d}";
export const LOGO_ROOF_STROKE = {sw:g};

/** Tight view box around the artwork, for placing it beside text. */
export const LOGO_VIEW_BOX = "{box}";
export const LOGO_ASPECT = {(x1 - x0) / (y1 - y0):.4f}; // width / height of LOGO_VIEW_BOX

export const LOGO_COLORS = {{
  navy: "#1B2430",
  paper: "#EFEAE0",
  brass: "#B08D57",
  brassDeep: "#8C6D3F",
}} as const;
''')
print(out, box)
